# ---------------- линейное контрастирование ----------------

def linear_contrast(g, p=0.0):
    """
    Линейное растяжение гистограммы: диапазон [lo, hi] -> [0, 255].
    Формула: g = (v − lo) · 255 / (hi − lo).

    p = 0   : lo = min, hi = max (классическое min–max растяжение).
    p > 0   : lo и hi — p-й и (100−p)-й процентили.

    КРИТИЧНО для защиты: зачем нужны процентили?
    Если на изображении есть 1-2 "битых" пикселя со значением 0 и 255 (шум),
    классическое min-max растяжение ничего не даст (диапазон и так полный).
    Процентиль отбрасывает крайние p% пикселей и растягивает "честный" диапазон.
    Например, p=1 отбрасывает 1% самых тёмных и 1% самых светлых пикселей.

    Возвращает (результат, lo, hi) — lo и hi нужны для отображения формулы в UI.
    """
    lo, hi = np.percentile(g, [p, 100 - p])

    # Защита от однотонного изображения (все пиксели одинаковые)
    if hi <= lo:
        return g.copy(), lo, hi

    # LUT-оптимизация: считаем таблицу перекодировки один раз
    lut = _clip((np.arange(256) - lo) * 255.0 / (hi - lo))
    return lut[g], lo, hi