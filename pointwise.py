# ---------------- операции над двумя изображениями одного размера ----------------

def image_sum(a, b):
    """Сумма с насыщением: a + b, не больше 255. Используется для наложения изображений."""
    return _clip(a.astype(np.int16) + b)


def image_diff(a, b):
    """Модуль разности |a − b| — показывает, чем изображения отличаются (детекция изменений)."""
    return np.abs(a.astype(np.int16) - b).astype(np.uint8)


def image_mean(a, b):
    """Среднее (a + b) / 2 — «смешивание» изображений (усреднение для подавления шума)."""
    return _clip((a.astype(np.float64) + b) / 2)


