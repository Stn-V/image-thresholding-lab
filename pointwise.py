""""
pointwise.py — Processing Layer (Слой обработки).

Реализует поэлементные операции и линейное контрастирование.
Архитектура:  Processing Layer — чистые математические функции,
которые принимают пиксельный буфер и возвращают новый, ничего не зная про UI.

Векторизация через numpy (требование группы 10А):
"""
import numpy as np

def _clip(a):
    """
    Обрезка до 0..255 и приведение к uint8.

    КРИТИЧНО для защиты: почему нельзя просто сложить два uint8 массива?
    uint8 хранит значения 0-255. Если сложить 250 + 20, получится 270, но uint8
    переполнится по модулю 256 и вернет 14 (270 - 256). Это называется "wrap-around".
    Поэтому промежуточные вычисления делаем в int16/float64, потом обрезаем и приводим к uint8.
    """
    return np.clip(np.rint(a), 0, 255).astype(np.uint8)

# ---------------- операции над одним изображением (value — параметр) ----------------

def add_const(g, c):
    """
    g = v + c — изменение яркости.
    """
    return _clip(g.astype(np.int16) + c)


def multiply(g, k):
    """
    g = k * v — изменение контраста.
    """
    return _clip(g.astype(np.float64) * k)

def negative(g, _=None):
    """g = 255 − v — негатив. Здесь переполнения нет (255 - 0 = 255, 255 - 255 = 0)."""
    return 255 - g


def gamma(g, gm):
    """
    g = 255 · (v/255)^γ — гамма-коррекция.
    LUT-оптимизация: вместо возведения в степень для каждого пикселя (дорогая операция),
    считаем 256 значений один раз, потом применяем через lut[g].
    γ < 1 осветляет тёмные участки (полезно для тёмных фото).
    γ > 1 затемняет светлые (полезно для пересвеченных фото).
    """
    lut = _clip(255 * (np.arange(256) / 255.0) ** gm)
    return lut[g]  # Индексация: для каждого пикселя берем значение из таблицы


def log_transform(g, _=None):
    """
    g = c · ln(1 + v), c = 255 / ln(256) — логарифмическое преобразование.
    LUT-оптимизация: логарифм — очень медленная операция. Считаем 256 значений,
    потом применяем через таблицу.
    Растягивает тёмные тона (полезно для изображений с высоким динамическим диапазоном).
    """
    lut = _clip(255 / np.log(256) * np.log1p(np.arange(256)))
    return lut[g]


def binarize(g, T):
    """Простейшая поэлементная бинаризация: v > T -> 255, иначе 0."""
    return np.where(g > T, 255, 0).astype(np.uint8)


